function eventsFor(shipment: Shipment): ShipmentEvent[] {
  const events: ShipmentEvent[] = [
    {
      id: `evt_${shipment.id}_1`,
      shipment_id: shipment.id,
      event_type: "status_change",
      from_status: null,
      to_status: "submitted",
      occurred_at: shipment.created_at,
      recorded_at: shipment.created_at,
      actor_display_name: "Demo Importer",
      note: null,
    },
  ];

  if (shipment.actual_arrival_at) {
    events.push({
      id: `evt_${shipment.id}_2`,
      shipment_id: shipment.id,
      event_type: "status_change",
      from_status: "submitted",
      to_status: "arrived",
      occurred_at: shipment.actual_arrival_at,
      recorded_at: shipment.actual_arrival_at,
      actor_display_name: "Demo Operator",
      note: "Vessel berthed.",
    });
  }

  if (shipment.actual_cleared_at) {
    events.push({
      id: `evt_${shipment.id}_3`,
      shipment_id: shipment.id,
      event_type: "status_change",
      from_status: "arrived",
      to_status: "cleared",
      occurred_at: shipment.actual_cleared_at,
      recorded_at: shipment.actual_cleared_at,
      actor_display_name: "Demo Operator",
      note: "Customs cleared.",
    });
  }

  return events;
}

export const mockShipmentDetails: ShipmentDetail[] = mockShipments.map(
  (shipment) => ({
    ...shipment,
    events: eventsFor(shipment),
  }),
);

export const mockShipmentEvents: ShipmentEvent[] = mockShipmentDetails.flatMap(
  (shipment) => shipment.events,
);
